#!/usr/bin/env python3
"""Regenerate runtime/gfx/kl_vulkan_features.h — every VkBool32-only feature
struct that extends VkPhysicalDeviceFeatures2, with each flag's name and offset.

klvk_CreateDevice uses it to diff what a guest ENABLES against what MoltenVK
REPORTS, flag by flag and by name, before the create call: MoltenVK stops at the
first missing flag ("the 11th flag in ..."), which names one gap per boot.

Structs come from the registry (vk.xml) and are kept only if the header the
runtime compiles against (MoltenVK's vulkan_core.h) declares them.

  tools/gen_vk_features.py [vk.xml] [vulkan_core.h]
"""
import os, re, sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
XML = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    "~/dev/klepton/vendor/third_party/vulkan-headers/src/registry/vk.xml")
HDR = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    ROOT, "vendor-moltenvk/out/include/vulkan/vulkan_core.h")
OUT = os.path.join(ROOT, "runtime/gfx/kl_vulkan_features.h")

hdr = open(HDR).read()
declared = set(re.findall(r"^\}\s*(Vk\w+);", hdr, re.M))
stypes = set(re.findall(r"^\s*(VK_STRUCTURE_TYPE_\w+)\s*=", hdr, re.M))

core = None
rows = []
for t in ET.parse(XML).getroot().iter("type"):
    if t.get("category") != "struct" or t.get("alias"):
        continue
    if t.get("name") == "VkPhysicalDeviceFeatures":
        core = [m.find("name").text for m in t.findall("member")]
        continue
    ext = (t.get("structextends") or "").split(",")
    if "VkPhysicalDeviceFeatures2" not in ext:
        continue
    name = t.get("name")
    if name not in declared:
        continue
    members = [m for m in t.findall("member") if m.get("api") in (None, "vulkan")]
    st = members[0].get("values")
    if not st or st not in stypes:
        continue
    flags = []
    ok = True
    for m in members[2:]:
        ty = m.find("type").text
        text = "".join(m.itertext())
        if ty != "VkBool32" or "[" in text:
            ok = False
            break
        flags.append(m.find("name").text)
    if ok and flags:
        rows.append((name, st, flags))

rows.sort()
with open(OUT, "w") as o:
    o.write("// GENERATED by tools/gen_vk_features.py — do not edit.\n")
    o.write("// %d VkBool32-only feature structs extending VkPhysicalDeviceFeatures2.\n" % len(rows))
    o.write("#pragma once\n#include <stddef.h>\n\n")
    o.write("typedef struct { const char *name; unsigned short off; } klvk_featflag;\n")
    o.write("typedef struct { VkStructureType stype; const char *name; size_t size;\n"
            "                 unsigned nflags; const klvk_featflag *flags; } klvk_featstruct;\n\n")
    for name, st, flags in rows:
        o.write("static const klvk_featflag klvkff_%s[] = {\n" % name)
        for f in flags:
            o.write("    {\"%s\", offsetof(%s, %s)},\n" % (f, name, f))
        o.write("};\n")
    o.write("\n// VkPhysicalDeviceFeatures (pEnabledFeatures, and inside VkPhysicalDeviceFeatures2).\n")
    o.write("static const klvk_featflag klvkff_core[] = {\n")
    for f in core:
        o.write("    {\"%s\", offsetof(VkPhysicalDeviceFeatures, %s)},\n" % (f, f))
    o.write("};\n")
    o.write("\nstatic const klvk_featstruct klvk_featstructs[] = {\n")
    for name, st, flags in rows:
        o.write("    {%s, \"%s\", sizeof(%s), %d, klvkff_%s},\n" % (st, name, name, len(flags), name))
    o.write("};\n")
print("wrote %s: %d structs" % (OUT, len(rows)))
